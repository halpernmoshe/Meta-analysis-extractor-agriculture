def load_all_matches():
    """Load and combine all dataset matches."""
    dfs = []
    loaders = [
        ('Loladze', load_loladze_matches),
        ('Hui', load_hui_matches),
        ('Li', load_li_matches),
        ('Biochar', load_biochar_matches),
        ('Boldorini', load_boldorini_matches),
    ]
    loaded = {}
    for name, loader in loaders:
        try:
            df = loader()
            if df is not None and len(df) > 0:
                dfs.append(df)
                loaded[name] = df
                print(f"  Loaded {name}: {len(df)} observations")
            else:
                print(f"  Skipped {name}: no data")
        except Exception as e:
            print(f"  Error loading {name}: {e}")

    combined = pd.concat(dfs, ignore_index=True) if dfs else None
    return combined, loaded


