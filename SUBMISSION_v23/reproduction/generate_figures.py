def generate_figure2(loaded_datasets):
    """Generate Figure 2: Scatter plots (one panel per dataset)."""
    datasets = [k for k in ['Loladze', 'Hui', 'Li', 'Biochar', 'Boldorini']
                if k in loaded_datasets]
    n_panels = len(datasets)
    if n_panels == 0:
        print("  Skipping Figure 2: no paired data available")
        return

    cols = min(n_panels, 3)
    rows = (n_panels + cols - 1) // cols
    fig, axes = plt.subplots(rows, cols, figsize=(5 * cols, 5 * rows), squeeze=False)
    fig.suptitle('Figure 2: Extracted vs. Ground-Truth Effect Sizes', fontsize=14,
                 fontweight='bold', y=1.02)

    for idx, name in enumerate(datasets):
        ax = axes[idx // cols][idx % cols]
        df = loaded_datasets[name]
        color = DATASET_COLORS.get(name, '#333')

        ax.scatter(df['gt_pct'], df['ext_pct'], alpha=0.4, s=15, c=color, edgecolors='none')

        # Identity line
        all_vals = pd.concat([df['gt_pct'], df['ext_pct']])
        vmin, vmax = all_vals.min(), all_vals.max()
        margin = (vmax - vmin) * 0.05
        ax.plot([vmin - margin, vmax + margin], [vmin - margin, vmax + margin],
                'k--', lw=1, alpha=0.6, label='Identity')

        # Compute r
        r = df['gt_pct'].corr(df['ext_pct'])
        n = len(df)
        display = DISPLAY_NAMES.get(name, name)
        ax.set_title(f'{display} (n={n}, r={r:.3f})', fontsize=11)
        ax.set_xlabel('Ground-truth effect (%)')
        ax.set_ylabel('Extracted effect (%)')

        # Add r annotation
        ax.text(0.05, 0.92, f'r = {r:.3f}', transform=ax.transAxes,
                fontsize=10, va='top',
                bbox=dict(boxstyle='round', facecolor='white', alpha=0.8))

    # Hide unused axes
    for idx in range(n_panels, rows * cols):
        axes[idx // cols][idx % cols].set_visible(False)

    plt.tight_layout()
    plt.savefig(os.path.join(FIGURES_DIR, 'figure2_scatter_plots.png'))
    plt.close()
    print(f"  Saved Figure 2: Scatter plots ({n_panels} panels)")


