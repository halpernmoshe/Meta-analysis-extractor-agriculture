def generate_figure4(loaded_datasets, formal_stats):
    """Generate Figure 4: Bland-Altman plots (one panel per dataset)."""
    datasets_with_data = [k for k in ['Loladze', 'Hui', 'Li', 'Biochar', 'Boldorini']
                          if k in loaded_datasets]
    n_panels = len(datasets_with_data)
    if n_panels == 0:
        print("  Skipping Figure 4: no paired data")
        return

    # Get Bland-Altman stats from formal_stats if available
    ba_stats = {}
    if formal_stats:
        for ds in formal_stats.get('datasets', []):
            short = ds['dataset'].split('(')[0].strip().split()[0]
            ba = ds.get('bland_altman', {})
            if ba.get('mean_bias') is not None:
                ba_stats[short] = ba

    cols = min(n_panels, 3)
    rows = (n_panels + cols - 1) // cols
    fig, axes = plt.subplots(rows, cols, figsize=(5 * cols, 5 * rows), squeeze=False)
    fig.suptitle('Figure 4: Bland-Altman Plots', fontsize=14, fontweight='bold', y=1.02)

    for idx, name in enumerate(datasets_with_data):
        ax = axes[idx // cols][idx % cols]
        df = loaded_datasets[name]
        color = DATASET_COLORS.get(name, '#333')

        diff = df['ext_pct'] - df['gt_pct']
        mean_val = (df['ext_pct'] + df['gt_pct']) / 2

        ax.scatter(mean_val, diff, alpha=0.4, s=15, c=color, edgecolors='none')

        mean_diff = diff.mean()
        sd_diff = diff.std()
        loa_upper = mean_diff + 1.96 * sd_diff
        loa_lower = mean_diff - 1.96 * sd_diff

        ax.axhline(y=mean_diff, color='black', linestyle='-', lw=1,
                   label=f'Bias = {mean_diff:.2f}')
        ax.axhline(y=loa_upper, color='red', linestyle='--', lw=1,
                   label=f'+1.96 SD = {loa_upper:.1f}')
        ax.axhline(y=loa_lower, color='red', linestyle='--', lw=1,
                   label=f'-1.96 SD = {loa_lower:.1f}')
        ax.axhline(y=0, color='gray', linestyle=':', lw=0.5)

        display = DISPLAY_NAMES.get(name, name)
        ax.set_title(f'{display} (n={len(df)})', fontsize=11)
        ax.set_xlabel('Mean of extracted and GT (%)')
        ax.set_ylabel('Difference (extracted - GT, pp)')
        ax.legend(fontsize=7, loc='upper right')

    for idx in range(n_panels, rows * cols):
        axes[idx // cols][idx % cols].set_visible(False)

    plt.tight_layout()
    plt.savefig(os.path.join(FIGURES_DIR, 'figure4_bland_altman.png'))
    plt.close()
    print(f"  Saved Figure 4: Bland-Altman plots ({n_panels} panels)")


