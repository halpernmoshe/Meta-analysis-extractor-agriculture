def generate_figure6(formal_stats):
    """Generate Figure 6: Aggregate effect reproduction (GT vs extracted)."""
    if formal_stats is None:
        print("  Skipping Figure 6: no formal stats")
        return

    datasets = formal_stats.get('datasets', [])
    if not datasets:
        return

    names = []
    gt_effects = []
    ext_effects = []

    for ds in datasets:
        short_name = ds['dataset'].split('(')[0].strip()
        if len(short_name) > 15:
            short_name = short_name[:15]
        # Use standardized display name
        short_name = DISPLAY_NAMES.get(short_name, short_name)
        oe = ds.get('overall_effect', {})
        gt_mean = oe.get('gt_mean')
        ext_mean = oe.get('ext_mean')
        if gt_mean is not None and ext_mean is not None:
            names.append(short_name)
            gt_effects.append(gt_mean)
            ext_effects.append(ext_mean)

    if not names:
        return

    fig, ax = plt.subplots(figsize=(10, 5))
    x = np.arange(len(names))
    width = 0.35

    bars1 = ax.bar(x - width/2, gt_effects, width, label='Ground Truth',
                   color='#1f77b4', edgecolor='black', linewidth=0.5)
    bars2 = ax.bar(x + width/2, ext_effects, width, label='Extracted',
                   color='#ff7f0e', edgecolor='black', linewidth=0.5)

    ax.set_ylabel('Mean Effect Size (%)')
    ax.set_title('Figure 6: Aggregate Effect Size Reproduction', fontsize=13,
                 fontweight='bold')
    ax.set_xticks(x)
    ax.set_xticklabels(names, rotation=30, ha='right', fontsize=9)
    ax.legend(fontsize=10)
    ax.axhline(y=0, color='gray', linestyle='-', lw=0.5)

    # Add difference annotations
    for i in range(len(names)):
        diff = abs(gt_effects[i] - ext_effects[i])
        y_pos = max(gt_effects[i], ext_effects[i])
        if y_pos < 0:
            y_pos = min(gt_effects[i], ext_effects[i]) - 1.5
        else:
            y_pos = y_pos + 1
        ax.text(i, y_pos, f'\u0394={diff:.2f} pp', ha='center', va='bottom',
                fontsize=8, color='#666')

    plt.tight_layout()
    plt.savefig(os.path.join(FIGURES_DIR, 'figure6_aggregate_effects.png'))
    plt.close()
    print("  Saved Figure 6: Aggregate effect reproduction")


