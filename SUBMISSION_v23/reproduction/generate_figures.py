def generate_figure3(formal_stats):
    """Generate Figure 3: Cross-dataset comparison bar chart."""
    if formal_stats is None:
        print("  Skipping Figure 3: no formal stats")
        return

    datasets = formal_stats.get('datasets', [])
    if not datasets:
        print("  Skipping Figure 3: empty datasets")
        return

    names = []
    r_vals = []
    mae_vals = []
    dir_vals = []

    for ds in datasets:
        short_name = ds['dataset'].split('(')[0].strip()
        if len(short_name) > 15:
            short_name = short_name[:15]
        # Use standardized display name
        short_name = DISPLAY_NAMES.get(short_name, short_name)
        names.append(short_name)
        r_vals.append(ds['pearson']['r'] if ds['pearson']['r'] else 0)
        mae_vals.append(ds['mae'] if ds['mae'] else 0)
        dir_pct = ds['direction']['pct'] if ds['direction']['pct'] else 0
        dir_vals.append(dir_pct)

    fig, axes = plt.subplots(1, 3, figsize=(14, 5))
    fig.suptitle('Figure 3: Cross-Dataset Validation Metrics', fontsize=14,
                 fontweight='bold')

    x = np.arange(len(names))
    colors = [list(DATASET_COLORS.values())[i % len(DATASET_COLORS)] for i in range(len(names))]

    # Panel A: Pearson r
    ax = axes[0]
    bars = ax.bar(x, r_vals, color=colors, edgecolor='black', linewidth=0.5)
    ax.set_xticks(x)
    ax.set_xticklabels(names, rotation=30, ha='right', fontsize=8)
    ax.set_ylabel('Pearson r')
    ax.set_title('A. Correlation')
    ax.set_ylim(0.7, 1.02)
    ax.axhline(y=0.9, color='gray', linestyle='--', alpha=0.5, label='r = 0.9')
    for i, v in enumerate(r_vals):
        ax.text(i, v + 0.005, f'{v:.3f}', ha='center', va='bottom', fontsize=8)
    ax.legend(fontsize=8)

    # Panel B: MAE
    ax = axes[1]
    ax.bar(x, mae_vals, color=colors, edgecolor='black', linewidth=0.5)
    ax.set_xticks(x)
    ax.set_xticklabels(names, rotation=30, ha='right', fontsize=8)
    ax.set_ylabel('MAE (pp)')
    ax.set_title('B. Mean Absolute Error')
    for i, v in enumerate(mae_vals):
        ax.text(i, v + 0.1, f'{v:.2f}', ha='center', va='bottom', fontsize=8)

    # Panel C: Direction agreement
    ax = axes[2]
    ax.bar(x, dir_vals, color=colors, edgecolor='black', linewidth=0.5)
    ax.set_xticks(x)
    ax.set_xticklabels(names, rotation=30, ha='right', fontsize=8)
    ax.set_ylabel('Direction Agreement (%)')
    ax.set_title('C. Direction Agreement')
    ax.set_ylim(75, 102)
    ax.axhline(y=90, color='gray', linestyle='--', alpha=0.5, label='90%')
    for i, v in enumerate(dir_vals):
        ax.text(i, v + 0.3, f'{v:.1f}%', ha='center', va='bottom', fontsize=8)
    ax.legend(fontsize=8)

    plt.tight_layout()
    plt.savefig(os.path.join(FIGURES_DIR, 'figure3_cross_dataset_comparison.png'))
    plt.close()
    print("  Saved Figure 3: Cross-dataset comparison")


