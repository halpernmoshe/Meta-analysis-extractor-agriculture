def load_formal_stats():
    """Load the formal_stats_all_datasets.json file (generated by formal_stats_all_datasets.py)."""
    path = os.path.join(SCRIPT_DIR, 'output', 'formal_stats_all_datasets.json')
    if not os.path.exists(path):
        print(f"WARNING: {path} not found. Some figures will be skipped.")
        return None
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)


def load_loladze_matches():
    """Load Loladze validation matches from LLM-aligned JSON."""
    path = os.path.join(OUTPUT_DIR, 'loladze_agent_replication', 'validation_llm_10pp.json')
    if not os.path.exists(path):
        print(f"WARNING: Loladze matches not found at {path}")
        return None
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    matched_obs = data.get('matched_observations', [])
    if not matched_obs:
        print("WARNING: No matched_observations in Loladze validation JSON")
        return None
    rows = []
    for obs in matched_obs:
        ext = obs.get('ext_effect_pct')
        gt = obs.get('gt_effect_pct')
        if ext is not None and gt is not None:
            rows.append({'ext_pct': float(ext), 'gt_pct': float(gt), 'dataset': 'Loladze'})
    if not rows:
        return None
    return pd.DataFrame(rows)


def load_hui_matches():
    """Load Hui validation matches CSV.
    Uses validation_matches_improved.csv (319 obs) which is the same file
    used by formal_stats_all_datasets.py.  Columns: ext_effect, gt_effect
    (percentage-point effect sizes).
    """
    improved_path = os.path.join(OUTPUT_DIR, 'hui2023_full_35', 'validation_matches_improved.csv')
    fallback_path = os.path.join(OUTPUT_DIR, 'hui2023_full_35', 'validation_matches.csv')
    path = improved_path if os.path.exists(improved_path) else fallback_path
    if not os.path.exists(path):
        print(f"WARNING: Hui matches not found at {improved_path}")
        return None
    df = pd.read_csv(path)
    if 'ext_effect' in df.columns and 'gt_effect' in df.columns:
        df['ext_pct'] = df['ext_effect']
        df['gt_pct'] = df['gt_effect']
    else:
        print(f"WARNING: Hui CSV missing expected columns (ext_effect, gt_effect). Found: {list(df.columns)}")
        return None
    df['dataset'] = 'Hui'
    return df[['ext_pct', 'gt_pct', 'dataset']].dropna()


def load_li_matches():
    """Load Li validation matches CSV.
    Uses validation_matches_effect_first.csv (117 obs) which is the same file
    used by formal_stats_all_datasets.py.  Columns: ext_effect_pct, gt_effect_pct.
    """
    path = os.path.join(OUTPUT_DIR, 'li2022_combined', 'validation_matches_effect_first.csv')
    if not os.path.exists(path):
        print(f"WARNING: Li matches not found at {path}")
        return None
    df = pd.read_csv(path)
    if 'gt_effect_pct' in df.columns and 'ext_effect_pct' in df.columns:
        df['ext_pct'] = df['ext_effect_pct']
        df['gt_pct'] = df['gt_effect_pct']
    else:
        print(f"WARNING: Li CSV missing expected columns. Found: {list(df.columns)}")
        return None
    df['dataset'] = 'Li'
    return df[['ext_pct', 'gt_pct', 'dataset']].dropna()


def load_biochar_matches():
    """Load biochar validation data from validation_results.json matched_observations."""
    path = os.path.join(OUTPUT_DIR, 'biochar_extraction', 'validation_results.json')
    if not os.path.exists(path):
        print(f"WARNING: Biochar validation not found at {path}")
        return None
    try:
        with open(path, 'r', encoding='utf-8') as f:
            data = json.load(f)
        obs = data.get('matched_observations', [])
        if not obs:
            print("WARNING: Biochar validation_results.json has no matched_observations")
            return None
        ext_vals = []
        gt_vals = []
        for m in obs:
            ev = m.get('ext_effect_pct')
            gv = m.get('gt_effect_pct')
            if ev is not None and gv is not None:
                ext_vals.append(float(ev))
                gt_vals.append(float(gv))
        if not ext_vals:
            print("WARNING: No valid paired values in biochar matched_observations")
            return None
        return pd.DataFrame({
            'ext_pct': ext_vals,
            'gt_pct': gt_vals,
            'dataset': 'Biochar'
        })
    except Exception as e:
        print(f"WARNING: Error loading biochar validation: {e}")
        return None


